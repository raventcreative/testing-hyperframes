"""production/words.json + assets/audio/vo.mp3 -> vendor/vo_words.js (VO_WORDS, VO_PHONES, VO_ENV, VO_SCENES, TOTAL) for the
mascot runtime (lip sync + acting) and vendor/words.js (WORDS, R38_TOTAL) for the scenes. Times include the VO offset (0.3 s).
Run from the project folder: python3 -I tools/vo_data.py"""
import json, re, subprocess
import numpy as np
OFF, TOTAL = 0.3, 47.6
W = json.load(open("production/words.json"))
PRON = {"ai": "ei", "ainya": "einya", "dm": "diem", "wifi": "waifai", "ruview": "ruviu", "github": "githab", "claude": "klod", "plugin": "plagin", "home": "hom",
        "assistant": "asisten", "mit": "emaiti", "open": "opn", "source": "sors", "laptop": "leptop", "code": "kod"}
EMPH = {"mendeteksi", "tembok.", "kamera", "RuView.", "seratus", "gini.", "napas,", "mengubah", "sembilan", "nebak:", "napasnya.", "Claude", "plugin",
        "lampu", "beta.", "kasar,", "akurat.", "penghuninya", "Komen", "DM."}
def sp(w):
    k = re.sub(r"[^a-z]", "", w.lower()); return PRON.get(k, k) or "a"
VW = [[w, round(s + OFF, 3), round(e + OFF, 3), 1 if w in EMPH else 0, sp(w)] for w, s, e in W]
PH = []
for i, (w, s, e, _, spk) in enumerate(VW):
    st = (e - s) / max(1, len(spk))
    for c, ch in enumerate(spk): PH.append([ch, round(s + c * st, 3), round(s + (c + 1) * st, 3), i])
pcm = subprocess.run(["ffmpeg", "-v", "error", "-i", "assets/audio/vo.mp3", "-ac", "1", "-ar", "16000", "-f", "s16le", "-"], capture_output=True, check=True).stdout
a = np.frombuffer(pcm, np.int16).astype(float) / 32768; hop = 160; n = len(a) // hop
db = 20 * np.log10(np.sqrt(np.mean(a[: n * hop].reshape(n, hop) ** 2, axis=1)) + 1e-6)
env = np.concatenate([np.zeros(int(OFF * 100)), np.clip((db + 60) / 60, 0, 1)])
SC = [{"id": "a", "start": 0, "dur": TOTAL, "w0": 0, "w1": len(VW) - 1}]
open("vendor/vo_words.js", "w").write("// generated by tools/vo_data.py (times include the VO offset)\nwindow.VO_WORDS = " + json.dumps(VW, ensure_ascii=False, separators=(",", ":")) +
    ";\nwindow.VO_PHONES = " + json.dumps(PH, separators=(",", ":")) + ";\nwindow.VO_ENV = " + json.dumps([int(round(v * 99)) for v in env], separators=(",", ":")) +
    ";\nwindow.VO_SCENES = " + json.dumps(SC, separators=(",", ":")) + ";\nwindow.TOTAL = " + str(TOTAL) + ";\n")
open("vendor/words.js", "w").write("// generated by tools/vo_data.py: [word, start, end] of the untouched VO take (file time; the take starts at 0.3 s)\nwindow.R38_TOTAL = " + str(TOTAL) +
    ";\nwindow.WORDS = " + json.dumps(W, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(len(VW), "words", len(PH), "phones", len(env), "env")
