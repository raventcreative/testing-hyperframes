"""Natural Earth 10m -> assets/maps/geo.js (clipped, Web Mercator, simplified, quantized).
Usage: python3 -I tools/build_geo.py <ne_dir> <project_dir>
Projection (shared by map, routes, markers, labels):
  X = (lon - LON0) * S
  Y = (M(LAT0) - M(lat)) * S * 180/pi,  M(lat) = ln(tan(pi/4 + lat/2))
"""
import json, math, sys, os
NE, OUT = sys.argv[1], sys.argv[2]
S, LON0, LAT0 = 40.0, 88.0, 12.0
BBOX = (80.0, -26.0, 160.0, 22.0)  # lon0, lat0, lon1, lat1 (clip edges stay off-screen)
Q = 20  # quantization: 1 unit = 1/20 base px
TOL = 0.0012  # DP tolerance in degrees (~130 m)

def M(lat): return math.log(math.tan(math.pi/4 + math.radians(lat)/2))
def proj(lon, lat): return ((lon-LON0)*S, (M(LAT0)-M(lat))*S*180/math.pi)

def clip(ring):
    # Sutherland-Hodgman against the bbox rectangle (lon/lat space)
    x0,y0,x1,y1 = BBOX
    edges = [(lambda p:p[0]>=x0, lambda a,b:(x0, a[1]+(b[1]-a[1])*(x0-a[0])/(b[0]-a[0]))),
             (lambda p:p[0]<=x1, lambda a,b:(x1, a[1]+(b[1]-a[1])*(x1-a[0])/(b[0]-a[0]))),
             (lambda p:p[1]>=y0, lambda a,b:(a[0]+(b[0]-a[0])*(y0-a[1])/(b[1]-a[1]), y0)),
             (lambda p:p[1]<=y1, lambda a,b:(a[0]+(b[0]-a[0])*(y1-a[1])/(b[1]-a[1]), y1))]
    out = ring
    for inside, inter in edges:
        inp, out = out, []
        if not inp: break
        prev = inp[-1]
        for cur in inp:
            if inside(cur):
                if not inside(prev): out.append(inter(prev, cur))
                out.append(cur)
            elif inside(prev): out.append(inter(prev, cur))
            prev = cur
    return out

def dp(pts, tol):
    if len(pts) < 4: return pts
    keep = [False]*len(pts); keep[0]=keep[-1]=True
    stack=[(0,len(pts)-1)]
    while stack:
        a,b = stack.pop()
        ax,ay = pts[a]; bx,by = pts[b]; dx,dy = bx-ax, by-ay; L = math.hypot(dx,dy) or 1e-12
        best,bi = -1,-1
        for i in range(a+1,b):
            px,py = pts[i]
            d = abs(dx*(ay-py)-dy*(ax-px))/L if L>1e-12 else math.hypot(px-ax,py-ay)
            if d>best: best,bi=d,i
        if best>tol:
            keep[bi]=True; stack += [(a,bi),(bi,b)]
    return [p for p,k in zip(pts,keep) if k]

def polys(geom):
    if geom['type']=='Polygon': return [geom['coordinates']]
    if geom['type']=='MultiPolygon': return geom['coordinates']
    return []

def encode(rings_lonlat):
    out=[]
    for r in rings_lonlat:
        r = clip([tuple(p[:2]) for p in r])
        if len(r)<3: continue
        r = dp(r+[r[0]], TOL)[:-1] if len(r)>3 else r
        if len(r)<3: continue
        flat=[]
        for lon,lat in r:
            x,y = proj(lon,lat); flat += [round(x*Q), round(y*Q)]
        out.append(flat)
    return out

def layer(path, pred=lambda p: True):
    d = json.load(open(os.path.join(NE,path)))
    rings=[]
    for f in d['features']:
        if not pred(f['properties']): continue
        for poly in polys(f['geometry']):
            rings += encode(poly)
    return rings

geo = {'S':S,'LON0':LON0,'LAT0':LAT0,'Q':Q,'bbox':BBOX,'source':'Natural Earth 10m (public domain), nvkelso/natural-earth-vector'}
geo['idn'] = layer('ne_10m_admin_0_countries.geojson', lambda p: p.get('ADM0_A3')=='IDN')
geo['other'] = layer('ne_10m_admin_0_countries.geojson', lambda p: p.get('ADM0_A3')!='IDN')
geo['bali'] = layer('ne_10m_admin_1_states_provinces.geojson', lambda p: p.get('adm0_a3')=='IDN' and p.get('name')=='Bali')
for k,f in [('b200','ne_10m_bathymetry_K_200.geojson'),('b1000','ne_10m_bathymetry_J_1000.geojson'),('b3000','ne_10m_bathymetry_H_3000.geojson')]:
    geo[k] = layer(f)
for k in ['idn','other','bali','b200','b1000','b3000']:
    print(k, len(geo[k]), 'rings', sum(len(r)//2 for r in geo[k]), 'pts')

# Bali anchor: area-weighted centroid of the largest Bali ring (main island), in lon/lat
d = json.load(open(os.path.join(NE,'ne_10m_admin_1_states_provinces.geojson')))
bali = [f for f in d['features'] if f['properties'].get('adm0_a3')=='IDN' and f['properties'].get('name')=='Bali'][0]
rings = [poly[0] for poly in polys(bali['geometry'])]
main = max(rings, key=len)
A=cx=cy=0
for (x0,y0),(x1,y1) in zip(main, main[1:]+main[:1]):
    c = x0*y1-x1*y0; A+=c; cx+=(x0+x1)*c; cy+=(y0+y1)*c
A/=2; cx/=6*A; cy/=6*A
lons=[p[0] for r in rings for p in r]; lats=[p[1] for r in rings for p in r]
print('bali centroid', cx, cy, 'bbox', min(lons),min(lats),max(lons),max(lats))
geo['baliBBox']=[min(lons),min(lats),max(lons),max(lats)]
geo['baliCentroid']=[cx,cy]
os.makedirs(os.path.join(OUT,'assets/maps'),exist_ok=True)
with open(os.path.join(OUT,'assets/maps/geo.js'),'w') as fh:
    fh.write('/* Natural Earth 10m, public domain. Generated by tools/build_geo.py */\nwindow.__GEO=')
    json.dump(geo, fh, separators=(',',':'))
    fh.write(';\n')
print('size', os.path.getsize(os.path.join(OUT,'assets/maps/geo.js')))
