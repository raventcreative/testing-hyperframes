"""Puppet rig for the front-facing AIpreneur robot: head, body, left hand, right hand (+ eye boxes, light spots).
Input is the background-free cutout from tools/cutout_robot.py. Head is split on a curve just above the collar with
a feathered seam (head layer and body layer sum to the original at rest). Coordinates are written in display px.
Run: python3 -I tools/cutout_robot.py assets/robot/robot2_src.webp /tmp/robot2_full.png
     python3 -I tools/rig_robot2.py /tmp/robot2_full.png <project> [display_width]"""
import json, sys
from collections import deque
from pathlib import Path
import numpy as np
from PIL import Image, ImageFilter

src, P = sys.argv[1], Path(sys.argv[2]).resolve()
DW = float(sys.argv[3]) if len(sys.argv) > 3 else 600
a = np.asarray(Image.open(src).convert("RGBA")).astype(np.float32); H, W = a.shape[:2]
rgb, al = a[..., :3], a[..., 3] / 255
yy, xx = np.mgrid[0:H, 0:W]
luma = 0.299 * rgb[..., 0] + 0.587 * rgb[..., 1] + 0.114 * rgb[..., 2]
sat = rgb.max(-1) - rgb.min(-1); tint = rgb[..., 2] - rgb[..., 0]
# leftover backdrop haze in a few known pockets
haze = (luma > 110) & (luma < 232) & (sat < 40) & (tint >= 8)
for x0, y0, x1, y1 in [(110, 190, 262, 425), (850, 170, 960, 260), (980, 440, 1069, 600)]:
    m = haze & (xx >= x0) & (xx < x1) & (yy >= y0) & (yy < y1); al[m] = 0

solid = al > 0.25
lab = np.zeros((H, W), np.int32); n = 0; comps = []
for sy, sx in zip(*np.nonzero(solid)):
    if lab[sy, sx]: continue
    n += 1; lab[sy, sx] = n; dq = deque([(sy, sx)]); c = 0
    while dq:
        y, x = dq.popleft(); c += 1
        for ny, nx in ((y - 1, x), (y + 1, x), (y, x - 1), (y, x + 1)):
            if 0 <= ny < H and 0 <= nx < W and solid[ny, nx] and not lab[ny, nx]: lab[ny, nx] = n; dq.append((ny, nx))
    comps.append((c, n))
comps.sort(reverse=True)
main_id, rhand_id = comps[0][1], comps[1][1]
al[(lab != main_id) & (lab != rhand_id) & solid] = 0               # drop specks
grow = lambda m, k=5: np.asarray(Image.fromarray((m * 255).astype(np.uint8)).filter(ImageFilter.MaxFilter(k))) > 0
rhand = grow(lab == rhand_id) & (al > 0)
lhand = (xx < 248) & (yy >= 560) & (yy <= 795) & (al > 0) & ~rhand
# head sits BEHIND the collar: body keeps everything below the collar line (hard edge on the real seam),
# head = everything above it plus a 14 px skirt that hides behind the collar when the head moves
curve = np.where((xx >= 255) & (xx <= 885), 442.0, 404.0)
inner = (xx >= 175) & (xx <= 925)
headw = ((yy < curve + 14) & inner & (al > 0)).astype(np.float32)
bodyw = (~((yy < curve) & inner)).astype(np.float32)
bodyw[lhand | rhand] = 0
EX = 0.62
F = DW / W


def layer(weight, name):
    A = (al * weight)
    m = A > 0.003
    ys, xs = np.nonzero(m); x0, y0, x1, y1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
    img = np.dstack([rgb, A * 255]).astype(np.uint8)[y0:y1, x0:x1]
    Image.fromarray(img, "RGBA").resize((max(1, round((x1 - x0) * EX)), max(1, round((y1 - y0) * EX))), Image.LANCZOS).save(P / f"assets/robot/r2_{name}.png", optimize=True)
    return [round(x0 * F, 1), round(y0 * F, 1), round((x1 - x0) * F, 1), round((y1 - y0) * F, 1)]


rig = {"w": DW, "h": round(H * F, 1)}
rig["body"] = layer(bodyw, "body")
rig["head"] = layer(headw, "head")
rig["lhand"] = layer(lhand.astype(np.float32), "lhand")
rig["rhand"] = layer(rhand.astype(np.float32), "rhand")
# eyes = bright blobs inside the visor
rig["eyes"] = [[round(x0 * F, 1), round(y0 * F, 1), round((x1 - x0) * F, 1), round((y1 - y0) * F, 1)] for x0, y0, x1, y1 in ((410, 203, 500, 347), (617, 203, 707, 347))]
rig["neck"] = [round(565 * F, 1), round(440 * F, 1)]
rig["chest"] = [round(330 * F, 1), round(625 * F, 1), round(500 * F, 1), round(120 * F, 1)]
rig["base"] = [round(420 * F, 1), round(990 * F, 1), round(260 * F, 1), round(45 * F, 1)]
(P / "vendor/robot_rig2.js").write_text("// generated by tools/rig_robot2.py\nwindow.ROBOT_RIG2 = " + json.dumps(rig) + ";\n")
print(json.dumps(rig))
