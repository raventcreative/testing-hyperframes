def extrude_text(id_, text, size, layers=10, step=1.6, weight=900, front="#fbfcfe", stroke="#acc6e7", ls=-0.02):
    """dimensional type: porcelain front face + navy sidewall made of stacked layers (needs a preserve-3d parent)."""
    out = [f'<div id="{id_}" class="p3" style="position:absolute;left:0;top:0;white-space:nowrap">']
    for k in range(layers, 0, -1):
        col = "#1c3354" if k > layers * 0.5 else "#294b77"
        out.append(f'<div style="position:absolute;left:0;top:0;font:{weight} {size}px Montserrat;letter-spacing:{ls}em;color:{col};transform:translateZ({r3(-k * step)}px)">{text}</div>')
    out.append(f'<div style="position:relative;font:{weight} {size}px Montserrat;letter-spacing:{ls}em;color:{front};-webkit-text-stroke:1.2px {stroke};'
               f'background:linear-gradient(170deg,#ffffff 0%,#eef3fa 60%,#d6e2f2 100%);-webkit-background-clip:text;background-clip:text;-webkit-text-fill-color:transparent">{text}</div>')
    out.append("</div>")
    return "".join(out)
