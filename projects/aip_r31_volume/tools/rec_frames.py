"""Client's real Instagram recording -> deterministic frame set for the B (konten) beat. LOCAL ONLY: reads
/home/user/testing-hyperframes/brand/rec/ig_aipreneur_academy_profile.mp4 and writes assets/rec/ig/*.jpg + assets/rec/ig_frames.js
(assets/rec/ is gitignored: the repo is public). Crop = the central IG column only (x 248..1656, y 122..935 of the 1920x1032 desktop
recording): no tabs / address bar / bookmarks / left sidebar (notification badge) / Messages widget.
Mapping (video time T -> source time): T < 16.55 header (src 2.0 + (T - 13.3), static profile + first row of 5 posts);
16.55..18.8 the post grid scrolls at an eased constant speed, picked by MEASURED scroll offset (phase-free row matching) so the
scroll is smooth even though the wheel steps in the source were jerky; 4-5x faster than real time."""
import json, subprocess, os, numpy as np
from PIL import Image
SRC = "/home/user/testing-hyperframes/brand/rec/ig_aipreneur_academy_profile.mp4"
CROP = (1408, 813, 248, 122); OUTW = 1200; FPS = 37.0
os.makedirs("assets/rec/ig", exist_ok=True)
def grab(t0, dur, w, gray):
    vf = f"crop={CROP[0]}:{CROP[1]}:{CROP[2]}:{CROP[3]},scale={w}:-2" + (",format=gray" if gray else ",format=rgb24")
    raw = subprocess.run(["ffmpeg", "-v", "error", "-ss", str(t0), "-t", str(dur), "-i", SRC, "-vf", vf, "-f", "rawvideo", "-"], capture_output=True, check=True).stdout
    h = round(CROP[1] * w / CROP[0] / 2) * 2; c = 1 if gray else 3
    return np.frombuffer(raw, np.uint8).reshape(-1, h, w, c) if c == 3 else np.frombuffer(raw, np.uint8).reshape(-1, h, w)
# 1) measure the scroll offset (crop px) from 15.0 to 26.7 s
T0 = 15.0; G = grab(T0, 11.7, 352, True).astype(float); off = [0.0]
for a, b in zip(G[:-1], G[1:]):
    best = (1e18, 0)
    for d in range(-8, 130):
        x = a[max(0, d):a.shape[0] + min(0, d)]; y = b[max(0, -d):b.shape[0] - max(0, d)]; h = min(len(x), len(y))
        e = np.mean((x[:h] - y[:h]) ** 2)
        if e < best[0]: best = (e, d)
    off.append(off[-1] + best[1])
off = np.array(off) * CROP[0] / 352; ts = T0 + np.arange(len(off)) / FPS
top = int(np.argmin(off[: int(1.2 * FPS)]))                 # last moment at the top of the page before the scroll
mono = np.maximum.accumulate(off[top:]); tsm = ts[top:]
O0, O1 = float(mono[0]), float(min(mono[-1], mono[0] + 3100))
def ease(u): u = min(1, max(0, u)); return u * u * (3 - 2 * u) * 0.35 + u * 0.65
def src_time(T):
    if T < 16.55: return round(2.0 + (T - 13.3), 1)          # header: 10 distinct frames per second is plenty (nearly static)
    o = O0 + (O1 - O0) * ease((T - 16.55) / 2.05); return float(tsm[int(np.searchsorted(mono, o))])
# 2) every source frame needed by the render (30 fps + the 3 motion-blur subframes) from 13.3 to 18.8 s
need = sorted({round(src_time(n / 30 + d) * FPS) for n in range(int(13.3 * 30), int(18.8 * 30) + 1) for d in (-1 / 90, 0, 1 / 90)})
fr = {}
for k in need:
    t = k / FPS; img = grab(t, 1 / FPS, OUTW, False)[0]; f = f"assets/rec/ig/s{k:04d}.jpg"
    Image.fromarray(img).save(f, quality=76); fr[k] = f
table = [[round(n / 30 + d, 4), fr[round(src_time(n / 30 + d) * FPS)]] for n in range(int(13.3 * 30), int(18.8 * 30) + 1) for d in (-1 / 90, 0, 1 / 90)]
table.sort()
open("assets/rec/ig_frames.js", "w").write("// generated by tools/rec_frames.py (LOCAL ONLY, gitignored)\nwindow.IG_FRAMES = " + json.dumps({"files": sorted(set(fr.values())), "table": table}) + ";\n")
print("frames", len(fr), "table", len(table), "scroll px", round(O1 - O0), "top at", round(ts[top], 2))
