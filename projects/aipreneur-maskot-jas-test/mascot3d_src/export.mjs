import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import fs from 'fs';
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);
const doc = await io.read(process.argv[2]);
const p = doc.getRoot().listMeshes()[0].listPrimitives()[0];
const out = process.argv[3];
fs.writeFileSync(out + '_pos.bin', Buffer.from(p.getAttribute('POSITION').getArray().buffer));
fs.writeFileSync(out + '_uv.bin', Buffer.from(p.getAttribute('TEXCOORD_0').getArray().buffer));
fs.writeFileSync(out + '_idx.bin', Buffer.from(new Uint32Array(p.getIndices().getArray()).buffer));
for (const t of doc.getRoot().listTextures()) fs.writeFileSync(out + '_' + (t.getName()||'tex').replace(/\.(jpg|png)$/,'') + '.' + t.getMimeType().split('/')[1], t.getImage());
console.log('ok', p.getAttribute('POSITION').getCount());
