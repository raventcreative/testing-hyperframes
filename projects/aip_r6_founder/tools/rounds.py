"""Builds vendor/rounds.js (window.ROUNDS, window.TOTAL, window.SCN) for the FOUNDER reel (R6).
ROUNDS = the three featured Founder skills, one per scene: s03 board (/founder-board), s04 CFO (/founder-cfo), s05 consumer panel
(/founder-consumer). tNum = first spoken word of the scene, tName = first underlined (c) or pill (m) word.
Run: python3 -I tools/rounds.py ."""
import json, sys
from pathlib import Path
P = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
T = json.loads((P / "production/timing.json").read_text()); W = T["words"]; S = {s["id"]: s for s in T["scenes"]}
R = []
for k, sid in enumerate(["s03", "s04", "s05"]):
    sc = S[sid]; ws = W[sc["w0"]:sc["w1"] + 1]
    name = next((w for w in ws if w["st"] in "cm"), ws[1])
    R.append({"k": k + 1, "id": sid, "start": sc["start"], "dur": sc["dur"], "tNum": ws[0]["s"], "tName": name["s"],
              "speechEnd": ws[-1]["e"], "words": [[w["w"], w["s"]] for w in ws]})
out = "// generated by tools/rounds.py (global times)\nwindow.ROUNDS = " + json.dumps(R, separators=(",", ":")) + ";\n"
out += f"window.TOTAL = {T['total_sec']};\nwindow.SCN = " + json.dumps({k: [v["start"], v["dur"]] for k, v in S.items()}, separators=(",", ":")) + ";\n"
(P / "vendor/rounds.js").write_text(out)
for r in R: print(r["id"], r["start"], r["tNum"], r["tName"], round(r["start"] + r["dur"], 3))
