"""Builds vendor/rounds.js (window.ROUNDS, window.TOTAL, window.SCN): the 5 STEPS (r1–r5) of the PROMPTBUILDER reel.
Per step: tNum = spoken number, tName = first cyan word, tUse = first word of the 2nd caption chunk (or tName), words. Run: python3 -I tools/rounds.py ."""
import json, sys
from pathlib import Path
P = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
T = json.loads((P / "production/timing.json").read_text()); W = T["words"]; S = {s["id"]: s for s in T["scenes"]}
R = []
for k in range(5):
    sc = S[f"r{k + 1}"]; ws = W[sc["w0"]:sc["w1"] + 1]
    name = next((w for w in ws if w["st"] == "c"), ws[1])
    R.append({"k": k + 1, "id": f"r{k + 1}", "start": sc["start"], "dur": sc["dur"], "tNum": ws[0]["s"], "tName": name["s"],
              "tUse": W[sc["cuts"][0]]["s"] if sc["cuts"] else name["s"], "speechEnd": ws[-1]["e"], "words": [[w["w"], w["s"]] for w in ws]})
out = "// generated by tools/rounds.py (global times)\nwindow.ROUNDS = " + json.dumps(R, separators=(",", ":")) + ";\n"
out += f"window.TOTAL = {T['total_sec']};\nwindow.SCN = " + json.dumps({k: [v["start"], v["dur"]] for k, v in S.items()}, separators=(",", ":")) + ";\n"
(P / "vendor/rounds.js").write_text(out)
for r in R: print(r["id"], r["start"], r["tNum"], r["tName"], r["tUse"], round(r["start"] + r["dur"], 3))
