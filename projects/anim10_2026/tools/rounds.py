"""Builds vendor/rounds.js (window.ROUNDS, window.HOOK, window.CTA) from production/timing.json: the single source of round timing
shared by the stage (sweeps + robot acting), the strip (chip unlocks), the round overlays, the SFX and the mascot.
Per round: tNum = the spoken number ("Satu,"), tName = the style name, sweep [s0, s1] ends right on the style name.
Run: python3 -I tools/rounds.py ."""
import json, sys
from pathlib import Path

P = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
T = json.loads((P / "production/timing.json").read_text())
W, S = T["words"], {s["id"]: s for s in T["scenes"]}
STY = [("lego", "Lego", "Style"), ("glow", "Glow", "Sketch"), ("comic", "Comic", "Art"), ("chalk", "Chalkboard", "Style"),
       ("pixel", "Pixel", "Art"), ("line", "Minimal", "Line"), ("explainer", "Explainer", "3D"), ("ps2", "PS2", "Style"),
       ("flat", "Flat", "Vector"), ("cgi", "CGI", "Motion")]
R = []
for k, (sid, a, b) in enumerate(STY):
    sc = S[f"r{k + 1}"]; ws = W[sc["w0"]:sc["w1"] + 1]
    num = ws[0]; name = next(w for w in ws if w["st"] == "c")
    last = ws[-1]
    s1 = round(name["s"] + 0.06, 3); s0 = round(s1 - 0.5, 3)
    R.append({"k": k + 1, "id": f"r{k + 1}", "style": sid, "name": f"{a} {b}", "a": a, "b": b, "start": sc["start"], "dur": sc["dur"],
              "tNum": num["s"], "tName": name["s"], "sweep": [s0, s1], "tDesc": W[sc["cuts"][0]]["s"], "speechEnd": last["e"]})
hook = S["s01"]; cta = S["s12"]
wt = lambda txt, after=0: next(w["s"] for w in W if w["w"] == txt and w["s"] >= after)
HOOK = {"start": 0, "dur": hook["dur"], "tRobot": wt("Robot"), "t10": wt("10"), "tAnimasi": wt("animasi."), "tClaude": wt("Claude."),
        "tTahan": wt("Tahan"), "t10b": wt("10.")}
CTA = {"start": cta["start"], "dur": cta["dur"], "tMau": wt("Mau"), "tKomen": wt("Komen"), "tPrompt": wt("PROMPT,"), "tDM": wt("DM.")}
out = "// generated by tools/rounds.py from production/timing.json (times include the VO offset)\n"
out += "window.ROUNDS = " + json.dumps(R, separators=(",", ":")) + ";\n"
out += "window.HOOK = " + json.dumps(HOOK, separators=(",", ":")) + ";\nwindow.CTA = " + json.dumps(CTA, separators=(",", ":")) + ";\n"
out += f"window.TOTAL = {T['total_sec']};\n"
(P / "vendor/rounds.js").write_text(out)
for r in R:
    print(f"{r['id']:>3} {r['style']:<9} start {r['start']:6.2f} num {r['tNum']:6.2f} name {r['tName']:6.2f} sweep {r['sweep'][0]:6.2f}-{r['sweep'][1]:6.2f} desc {r['tDesc']:6.2f} end {r['start'] + r['dur']:6.2f}")
print("HOOK", HOOK); print("CTA", CTA)
