"""Build effects/peta-kirim/map.js: a simplified Indonesia outline (Natural Earth 10m, public domain) as one SVG path.
Source: projects/indonesia-map-journey/assets/maps/geo.js (Natural Earth 10m country polygons, quantised).
Usage: python3 -I tools/make_map.py"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GEO = ROOT.parent / "indonesia-map-journey" / "assets" / "maps" / "geo.js"
W = 860                      # output width in px (map box)
LON_MIN, LON_MAX, LAT_MAX, LAT_MIN = 94.6, 141.2, 6.3, -11.2
K = W / (LON_MAX - LON_MIN)
H = round((LAT_MAX - LAT_MIN) * K)
TOL = 0.55                   # Douglas-Peucker tolerance (px)
MIN_AREA = 9.0               # drop islands smaller than this (px^2)


def proj(lon, lat):
    return ((lon - LON_MIN) * K, (LAT_MAX - lat) * K)


def dp(pts, tol):
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    n = (dx * dx + dy * dy) ** 0.5 or 1e-9
    best, idx = -1, 0
    for i in range(1, len(pts) - 1):
        x, y = pts[i]
        d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / n
        if d > best:
            best, idx = d, i
    if best > tol:
        return dp(pts[: idx + 1], tol)[:-1] + dp(pts[idx:], tol)
    return [pts[0], pts[-1]]


def area(pts):
    a = 0.0
    for i in range(len(pts)):
        x1, y1 = pts[i]
        x2, y2 = pts[(i + 1) % len(pts)]
        a += x1 * y2 - x2 * y1
    return abs(a) / 2


def main():
    txt = GEO.read_text()
    g = json.loads(re.search(r"window.__GEO=(\{.*\})", txt, re.S).group(1).rstrip(";"))
    S, Q, LON0, LAT0 = g["S"], g["Q"], g["LON0"], g["LAT0"]
    parts, kept = [], 0
    for poly in g["idn"]:
        pts = [proj(LON0 + poly[i] / (Q * S), LAT0 - poly[i + 1] / (Q * S)) for i in range(0, len(poly), 2)]
        if area(pts) < MIN_AREA:
            continue
        m = len(pts) // 2
        s = dp(pts[: m + 1], TOL)[:-1] + dp(pts[m:] + [pts[0]], TOL)[:-1]
        if len(s) < 3:
            continue
        kept += 1
        parts.append("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in s) + "Z")
    d = "".join(parts)
    # neighbours (lighter, context only): any polygon of g["other"] that touches the map box
    nb = []
    for poly in g["other"]:
        pts = [proj(LON0 + poly[i] / (Q * S), LAT0 - poly[i + 1] / (Q * S)) for i in range(0, len(poly), 2)]
        if area(pts) < MIN_AREA * 4 or not any(-40 < x < W + 40 and -40 < y < H + 40 for x, y in pts):
            continue
        m = len(pts) // 2
        s = dp(pts[: m + 1], TOL * 1.6)[:-1] + dp(pts[m:] + [pts[0]], TOL * 1.6)[:-1]
        if len(s) >= 3:
            nb.append("M" + "L".join(f"{x:.0f} {y:.0f}" for x, y in s) + "Z")
    d2 = "".join(nb)
    js = ("// generated by tools/make_map.py: Indonesia outline from Natural Earth 10m (public domain)\n"
          f"window.MAP_IDN = {{ w: {W}, h: {H}, k: {K:.5f}, lonMin: {LON_MIN}, latMax: {LAT_MAX}, d: \"{d}\", nb: \"{d2}\" }};\n")
    out = ROOT / "effects" / "peta-kirim" / "map.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(js)
    print("polys", kept, "bytes", len(js), "size", W, H)


if __name__ == "__main__":
    main()
