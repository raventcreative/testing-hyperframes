#!/usr/bin/env python3
"""Insert a no-VO SHOWCASE gap into the timeline (the voice-over itself is never cut inside a word, stretched or sped up).
The VO is split at a measured silence (CUT, between "hidup." and "Kalau"); everything spoken after CUT plays GAP seconds
later. Run after tools/vo_align.py (it rewrites the un-gapped originals, kept here as *_base.json on first run).
  production/word_timing.json, phoneme_timing.json, vendor/vo_words.js, production/scenes.json  <- shifted
  production/gap.json  {cut, gap}  <- read by gen_root (two VO clips), gen_sfx (VO level map), gen_world (showcase)"""
import json, re, shutil
from pathlib import Path
P = Path(__file__).resolve().parents[1]
CUT, GAP = 18.06, 11.0          # silence 17.82..18.34 s; showcase length
SHOW_SCENE = "s05"              # the scene that holds the showcase (extended by GAP)

prod = P / "production"
for n in ("word_timing", "phoneme_timing", "scenes"):
    if not (prod / f"{n}_base.json").exists():
        shutil.copy(prod / f"{n}.json", prod / f"{n}_base.json")
if not (P / "vendor/vo_words_base.js").exists():
    shutil.copy(P / "vendor/vo_words.js", P / "vendor/vo_words_base.js")
sh = lambda t: round(t + GAP, 3) if t >= CUT else t

wt = json.loads((prod / "word_timing_base.json").read_text())
for w in wt["words"]:
    w["start"], w["end"] = sh(w["start"]), sh(w["end"])
cg = wt["caption_groups"]
for i, g in enumerate(cg):
    pre = g["start"] < CUT
    g["start"] = sh(g["start"])
    g["end"] = round(CUT + 0.1, 3) if pre and g["end"] >= CUT else sh(g["end"])   # last pre-gap line leaves with the voice
wt["caption_groups"] = cg
wt["last_word_end"] = wt["words"][-1]["end"]
wt["gap"] = {"cut": CUT, "gap": GAP}
(prod / "word_timing.json").write_text(json.dumps(wt, indent=1, ensure_ascii=False))

ph = json.loads((prod / "phoneme_timing_base.json").read_text())
ph["phones"] = [[p[0], sh(p[1]), sh(p[2]) if p[1] >= CUT else p[2], *p[3:]] for p in ph["phones"]]
(prod / "phoneme_timing.json").write_text(json.dumps(ph, indent=0))

js = (P / "vendor/vo_words_base.js").read_text()
def arr(name):
    m = re.search(r"window\." + name + r" = (\[.*?\]);", js, re.S)
    return json.loads(m.group(1))
vw, phones, env = arr("VO_WORDS"), arr("VO_PHONES"), arr("VO_ENV")
vw = [[w[0], sh(w[1]), sh(w[2]), *w[3:]] for w in vw]
phones = [[p[0], sh(p[1]), sh(p[2]) if p[1] >= CUT else p[2], *p[3:]] for p in phones]
k = int(round(CUT * 100))
env = env[:k] + [0] * int(round(GAP * 100)) + env[k:]
(P / "vendor/vo_words.js").write_text(
    "// generated by tools/vo_align.py + tools/insert_gap.py (showcase gap %.2f s at %.2f s)\n" % (GAP, CUT) +
    "window.VO_WORDS = " + json.dumps(vw, separators=(",", ":"), ensure_ascii=False) + ";\n"
    "window.VO_PHONES = " + json.dumps(phones, separators=(",", ":")) + ";\n"
    "window.VO_ENV = " + json.dumps(env, separators=(",", ":")) + "; // 100 Hz, 0..99 = -60..0 dB\n")

sc = json.loads((prod / "scenes_base.json").read_text())
for s in sc["scenes"]:
    if s["id"] == SHOW_SCENE:
        s["end"] = round(s["end"] + GAP, 4); s["dur"] = round(s["end"] - s["start"], 4); s["label"] += " + SHOWCASE"
    elif s["start"] >= CUT - 0.1:
        s["start"] = round(s["start"] + GAP, 4); s["end"] = round(s["end"] + GAP, 4)
sc["duration"] = round(sc["duration"] + GAP, 4)
sc["gap"] = {"cut": CUT, "gap": GAP}
(prod / "scenes.json").write_text(json.dumps(sc, indent=1))
(prod / "gap.json").write_text(json.dumps({"cut": CUT, "gap": GAP}))
print("gap", GAP, "at", CUT, "-> duration", sc["duration"], [(s["id"], s["start"], s["end"]) for s in sc["scenes"]])
