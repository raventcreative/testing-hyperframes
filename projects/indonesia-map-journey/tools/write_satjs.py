"""Rewrite data/sat.js from data/sat.json (only entries whose image exists)."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
man = json.load(open(os.path.join(ROOT, "data", "sat.json")))
man = {k: v for k, v in man.items() if os.path.exists(os.path.join(ROOT, v["file"]))}
with open(os.path.join(ROOT, "data", "sat.js"), "w") as fh:
    fh.write("/* generated by tools/bake_satellite.py */\nwindow.__SAT=" + json.dumps({k: {kk: v[kk] for kk in ("file", "world", "px", "kHold")} for k, v in man.items()}) + ";\n")
print("sat.js:", sorted(man))
