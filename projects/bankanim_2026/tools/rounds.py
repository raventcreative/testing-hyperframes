"""Builds vendor/rounds.js (window.ROUNDS, window.TOTAL) from production/timing.json: the shared timing of the 12 animation rounds,
used by the strip layer, the round overlays (r1–r12), the SFX and the characters. Per round: tNum = spoken number, tName = the
animation's name, tUse = first word of the "what it's for" line, speechEnd. Run: python3 -I tools/rounds.py ."""
import json, sys
from pathlib import Path
P = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
T = json.loads((P / "production/timing.json").read_text()); W = T["words"]; S = {s["id"]: s for s in T["scenes"]}
TYPES = ["check", "loading", "counter", "bell", "chart", "toggle", "heart", "ring", "typing", "upload", "search", "stars"]
R = []
for k, ty in enumerate(TYPES):
    sc = S[f"r{k + 1}"]; ws = W[sc["w0"]:sc["w1"] + 1]
    name = next(w for w in ws if w["st"] == "c")
    R.append({"k": k + 1, "id": f"r{k + 1}", "type": ty, "start": sc["start"], "dur": sc["dur"], "tNum": ws[0]["s"], "tName": name["s"],
              "tUse": W[sc["cuts"][0]]["s"], "speechEnd": ws[-1]["e"], "words": [[w["w"], w["s"]] for w in ws]})
out = "// generated by tools/rounds.py (global times, VO offset included)\nwindow.ROUNDS = " + json.dumps(R, separators=(",", ":")) + ";\n"
out += f"window.TOTAL = {T['total_sec']};\nwindow.SCN = " + json.dumps({k: [v["start"], v["dur"]] for k, v in S.items()}, separators=(",", ":")) + ";\n"
(P / "vendor/rounds.js").write_text(out)
for r in R: print(f"{r['id']:>3} {r['type']:<8} start {r['start']:6.2f} num {r['tNum']:6.2f} name {r['tName']:6.2f} use {r['tUse']:6.2f} end {r['start'] + r['dur']:6.2f}")
