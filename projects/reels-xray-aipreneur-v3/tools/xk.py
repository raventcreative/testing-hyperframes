"""X-RAY kit: deterministic builders for the Ice-Ivory diorama scenes.

A scene module (tools/scenes/sNN.py) defines build(S) and uses:
  S.far / S.mid / S.near   lists of HTML strings (three depth planes inside the 3D camera)
  S.css                    list of CSS rules (ids are prefixed with the scene id)
  S.init(sel, props)       gsap.set at build time (frame-zero state)
  S.ft(sel, frm, to, at, dur, ease="power2.out")   tl.fromTo with GLOBAL time `at` (converted to local)
  S.W(i) / S.WE(i)         measured VO word start / end (global seconds)
  S.cam(keys)              camera keyframes on #<id>-cam: [(t, {z, rotationY, rotationX, x, y, scale}, ease)]
Everything is a function of timeline time (no random, no timers).
"""
import json, math
from pathlib import Path

P = Path(__file__).resolve().parents[1]
WT = json.loads((P / "production/word_timing.json").read_text())
WORDS = WT["words"]
SCENES = json.loads((P / "production/scenes.json").read_text())


def r3(x):
    s = f"{x:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def js(d):
    """python dict -> JS object literal (numbers rounded)."""
    def fix(v):
        if isinstance(v, float):
            return float(r3(v))
        if isinstance(v, dict):
            return {k: fix(x) for k, x in v.items()}
        if isinstance(v, list):
            return [fix(x) for x in v]
        return v
    return json.dumps(fix(d), ensure_ascii=False)


class Rng:  # small LCG, seeded -> reproducible decoration layouts
    def __init__(self, seed):
        self.s = seed & 0x7FFFFFFF or 1
    def f(self):
        self.s = (1103515245 * self.s + 12345) & 0x7FFFFFFF
        return self.s / 0x7FFFFFFF
    def u(self, a, b):
        return a + (b - a) * self.f()


class Scene:
    def __init__(self, sid):
        meta = next(s for s in SCENES["scenes"] if s["id"] == sid)
        self.id, self.t0, self.t1 = sid, meta["start"], meta["end"]
        self.host0 = 0.0 if self.t0 <= 0 else round(self.t0 - 0.001, 4)
        self.far, self.mid, self.near, self.css, self._init, self._tl = [], [], [], [], [], []
        self.persp_origin = (590, 900)

    # -------- time
    def W(self, i):
        return WORDS[i]["start"]
    def WE(self, i):
        return WORDS[i]["end"]
    def L(self, t):
        return max(0.0, t - self.host0)
    @property
    def dur(self):
        return self.t1 - self.host0

    # -------- tweens
    def init(self, sel, props):
        self._init.append(f"gsap.set({json.dumps(sel)}, {js(props)});")
    def ft(self, sel, frm, to, at, dur, ease="power2.out"):
        to = dict(to, duration=dur, ease=ease, immediateRender=False)
        self._tl.append(f"tl.fromTo({json.dumps(sel)}, {js(frm)}, {js(to)}, {r3(self.L(at))});")
    def tset(self, sel, props, at):
        self._tl.append(f"tl.set({json.dumps(sel)}, {js(props)}, {r3(self.L(at))});")
    def raw(self, line):
        self._tl.append(line)
    def keys(self, sel, keys, start_props=None):
        """chain of fromTo between keyframes: keys = [(t, props, ease)], first key = initial state."""
        t_prev, p_prev = keys[0][0], dict(keys[0][1])
        self.init(sel, p_prev)
        for t, p, ease in keys[1:]:
            full = dict(p_prev); full.update(p)
            self.ft(sel, p_prev, full, t_prev, max(0.01, t - t_prev), ease)
            t_prev, p_prev = t, full
    def cam(self, keys):
        self.keys(f"#{self.id}-cam", keys)

    # -------- write
    def write(self):
        sid = self.id
        ox, oy = self.persp_origin
        doc = f"""<template>
  <style>
    #root {{ position: absolute; inset: 0; }}
    #{sid}-persp {{ perspective-origin: {ox}px {oy}px; }}
    {chr(10).join('    ' + c for c in self.css).strip()}
  </style>
  <div id="root" class="xr-root" data-composition-id="{sid}" data-width="1080" data-height="1920">
    <div class="xr-persp" id="{sid}-persp" data-layout-ignore>
      <div class="xr-cam" id="{sid}-cam" data-layout-ignore>
        <div class="xr-layer" id="{sid}-far" data-layout-ignore>
{chr(10).join('          ' + h for h in self.far)}
        </div>
        <div class="xr-layer" id="{sid}-mid" data-layout-ignore>
{chr(10).join('          ' + h for h in self.mid)}
        </div>
        <div class="xr-layer" id="{sid}-near" data-layout-ignore>
{chr(10).join('          ' + h for h in self.near)}
        </div>
      </div>
    </div>
  </div>
  <script>
    (function () {{
      // generated by tools/build_scenes.py from tools/scenes/{sid}.py — local time 0 = scene start ({r3(self.host0)} s)
      const tl = gsap.timeline({{ paused: true }});
      {(chr(10) + '      ').join(self._init)}
      {(chr(10) + '      ').join(self._tl)}
      tl.set({{}}, {{}}, {r3(self.dur - 0.004)});
      window.__timelines = window.__timelines || {{}};
      window.__timelines["{sid}"] = tl;
    }})();
  </script>
</template>
"""
        (P / f"compositions/{sid}.html").write_text(doc)


# ======================================================================= HTML part helpers
def div(id_=None, cls="", style="", inner="", extra=""):
    i = f' id="{id_}"' if id_ else ""
    c = f' class="{cls}"' if cls else ""
    s = f' style="{style}"' if style else ""
    return f"<div{i}{c}{s}{extra}>{inner}</div>"


def box(x, y, w, h):
    return f"left:{r3(x)}px;top:{r3(y)}px;width:{r3(w)}px;height:{r3(h)}px;"


def screw(x, y, rot=35, size=14):
    return f'<div class="screw" style="left:{r3(x - size / 2)}px;top:{r3(y - size / 2)}px;width:{size}px;height:{size}px;--r:{rot}deg"></div>'


def screws_rect(x, y, w, h, inset=16, rots=(35, -20, 60, 10), size=14):
    return "".join(screw(px, py, r, size) for (px, py), r in zip(
        [(x + inset, y + inset), (x + w - inset, y + inset), (x + inset, y + h - inset), (x + w - inset, y + h - inset)], rots))


def shadow(x, y, w, h, op=1.0, soft=False, id_=None):
    i = f' id="{id_}"' if id_ else ""
    return f'<div{i} class="{"shadow-soft" if soft else "shadow"}" style="{box(x, y, w, h)}opacity:{op}"></div>'


def rivets_line(x0, y0, x1, y1, n):
    out = []
    for k in range(n):
        u = k / max(1, n - 1)
        out.append(f'<div class="rivet" style="left:{r3(x0 + (x1 - x0) * u - 4)}px;top:{r3(y0 + (y1 - y0) * u - 4)}px"></div>')
    return "".join(out)


def gear_path(r_out, r_in, teeth, cx=0, cy=0, tooth=0.42):
    """closed SVG path of a spur gear centred at (cx, cy)."""
    pts = []
    for k in range(teeth):
        a0 = 2 * math.pi * k / teeth
        da = 2 * math.pi / teeth
        for (frac, r) in ((0.0, r_in), (0.5 - tooth / 2 - 0.06, r_in), (0.5 - tooth / 2, r_out), (0.5 + tooth / 2, r_out), (0.5 + tooth / 2 + 0.06, r_in)):
            a = a0 + da * frac
            pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return "M" + " L".join(f"{r3(px)},{r3(py)}" for px, py in pts) + " Z"


def gear_svg(id_, size, teeth, hole=0.26, spokes=5, fill_id=None, stroke="#9fb6d6"):
    """porcelain gear with navy hub; rotate the <svg> (or its wrapper) with GSAP."""
    R = size / 2
    gid = fill_id or f"{id_}-g"
    p = gear_path(R - 1, R * 0.84, teeth, R, R)
    sp = []
    for k in range(spokes):
        a = 2 * math.pi * k / spokes + 0.3
        sp.append(f'<circle cx="{r3(R + R * 0.55 * math.cos(a))}" cy="{r3(R + R * 0.55 * math.sin(a))}" r="{r3(R * 0.13)}" fill="#e3ebf7" stroke="#b9cbe4" stroke-width="1.2"/>')
    return (f'<svg id="{id_}" width="{size}" height="{size}" viewBox="0 0 {size} {size}" style="position:absolute;overflow:visible">'
            f'<defs><linearGradient id="{gid}" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#ffffff"/><stop offset=".55" stop-color="#eaf0f9"/><stop offset="1" stop-color="#c9d8ee"/></linearGradient>'
            f'<radialGradient id="{gid}h" cx=".38" cy=".34" r=".7"><stop offset="0" stop-color="#5d84b9"/><stop offset="1" stop-color="#1c3354"/></radialGradient></defs>'
            f'<path d="{p}" fill="url(#{gid})" stroke="{stroke}" stroke-width="1.5"/>'
            f'<circle cx="{R}" cy="{R}" r="{r3(R * 0.72)}" fill="none" stroke="#d3dff0" stroke-width="2"/>'
            + "".join(sp) +
            f'<circle cx="{R}" cy="{R}" r="{r3(R * hole)}" fill="url(#{gid}h)"/>'
            f'<circle cx="{R}" cy="{R}" r="{r3(R * hole * 0.35)}" fill="#e8f0fb"/></svg>')


