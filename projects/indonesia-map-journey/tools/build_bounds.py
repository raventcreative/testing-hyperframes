"""Official administrative boundaries for the eight destinations -> assets/maps/bounds.js
Source: geoBoundaries gbOpen IDN (BPS - Statistics Indonesia, WFP, OCHA ROAP), CC BY 3.0 IGO.
  cities: ADM2 "Kota ..." polygons (full resolution); Jakarta = union of its five kota (Kepulauan Seribu excluded);
  Bali: ADM1 province polygon (regional view).
Also NE 10m lakes + land boundary lines for the relief basemap.
Usage: python3 -I tools/build_bounds.py <geoboundaries_dir> <naturalearth_dir>
"""
import json, math, os, sys
from shapely.geometry import shape, mapping
from shapely.ops import unary_union

GB, NE = sys.argv[1], sys.argv[2]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S, LON0, LAT0, Q = 40.0, 88.0, 12.0, 20
M = lambda la: math.log(math.tan(math.pi / 4 + math.radians(la) / 2))
def proj(lon, lat): return (lon - LON0) * S, (M(LAT0) - M(lat)) * S * 180 / math.pi

CITY = {"surabaya": ["Kota Surabaya"], "medan": ["Kota Medan"], "solo": ["Kota Surakarta"], "bandung": ["Kota Bandung"],
        "yogyakarta": ["Kota Yogyakarta"], "makassar": ["Kota Makassar"],
        "jakarta": ["Kota Jakarta Barat", "Kota Jakarta Pusat", "Kota Jakarta Selatan", "Kota Jakarta Timur", "Kota Jakarta Utara"]}

def rings(geom, tol):
    geom = geom.simplify(tol, preserve_topology=True)
    polys = [geom] if geom.geom_type == "Polygon" else list(geom.geoms)
    out = []
    for p in polys:
        for r in [p.exterior] + list(p.interiors):
            flat = []
            for lon, lat in list(r.coords)[:-1]:
                x, y = proj(lon, lat); flat += [round(x * Q), round(y * Q)]
            if len(flat) >= 6: out.append(flat)
    return out

adm2 = json.load(open(os.path.join(GB, "IDN_ADM2.geojson")))
byname = {}
for f in adm2["features"]:
    byname.setdefault(f["properties"]["shapeName"], []).append(shape(f["geometry"]))
out = {"source": "geoBoundaries gbOpen IDN ADM2/ADM1 (BPS, WFP, OCHA ROAP), CC BY 3.0 IGO"}
for cid, names in CITY.items():
    parts = [g for n in names for g in byname[n]]
    u = unary_union(parts).buffer(0)
    # keep the main landmass + parts bigger than 1 % of it (drops stray islets, e.g. off Makassar)
    polys = [u] if u.geom_type == "Polygon" else sorted(u.geoms, key=lambda g: -g.area)
    keep = [p for p in polys if p.area >= polys[0].area * 0.01]
    u = unary_union(keep)
    c = u.centroid
    out[cid] = {"outer": rings(u, 0.0004), "parts": [rings(p, 0.0004) for p in parts] if len(parts) > 1 else [],
                "names": names, "centroid": [c.x, c.y], "bbox": list(u.bounds)}
    print(cid, names, "rings", len(out[cid]["outer"]), "pts", sum(len(r) // 2 for r in out[cid]["outer"]), "bbox", [round(v, 3) for v in u.bounds])

adm1 = json.load(open(os.path.join(GB, "IDN_ADM1_simplified.geojson")))
bali = unary_union([shape(f["geometry"]) for f in adm1["features"] if f["properties"]["shapeName"] == "Bali"])
out["bali"] = {"outer": rings(bali, 0.0006), "parts": [], "names": ["Provinsi Bali"], "centroid": [bali.centroid.x, bali.centroid.y], "bbox": list(bali.bounds)}
print("bali rings", len(out["bali"]["outer"]), "bbox", [round(v, 3) for v in bali.bounds])

def ne_rings(fn, pred=lambda p: True, lines=False):
    d = json.load(open(os.path.join(NE, fn)))
    res = []
    for f in d["features"]:
        g = shape(f["geometry"])
        if not pred(f["properties"]) or not g.intersects(shape({"type": "Polygon", "coordinates": [[[80, -26], [160, -26], [160, 22], [80, 22], [80, -26]]]})):
            continue
        if lines:
            ls = [g] if g.geom_type == "LineString" else list(g.geoms)
            for l in ls:
                flat = []
                for lon, lat in l.coords:
                    x, y = proj(lon, lat); flat += [round(x * Q), round(y * Q)]
                res.append(flat)
        else:
            res += rings(g, 0.001)
    return res

out["lakes"] = ne_rings("ne_10m_lakes.geojson")
out["borders"] = ne_rings("ne_10m_admin_0_boundary_lines_land.geojson", lines=True)
print("lakes", len(out["lakes"]), "borders", len(out["borders"]))
with open(os.path.join(ROOT, "assets", "maps", "bounds.js"), "w") as fh:
    fh.write("/* generated by tools/build_bounds.py — geoBoundaries (CC BY 3.0 IGO) + Natural Earth (public domain) */\nwindow.__BOUNDS=")
    json.dump(out, fh, separators=(",", ":"))
    fh.write(";\n")
print("size", os.path.getsize(os.path.join(ROOT, "assets", "maps", "bounds.js")))
