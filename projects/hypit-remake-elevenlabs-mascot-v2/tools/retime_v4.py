"""v4 re-timing: make the audio-measured phoneme alignment the master clock.

Inputs : production/phoneme_timing.json (tools/phoneme_align.py, CTC forced alignment on the real VO)
         assets/vo_elevenlabs_final.mp3 (energy envelope)
Outputs: production/word_timing.json (words + caption groups re-timed; v3 copy kept as word_timing_v3_estimated.json)
         production/timing_warp_v4.json (old word start -> new word start, used to re-time scene hits)
         vendor/vo_words.js  (window.VO_WORDS, VO_PHONES, VO_ENV 100 Hz energy, VO_WARP)
         tools/sfx_plan.json apexes warped onto the new timing
"""
import json, shutil, subprocess, sys
from pathlib import Path
import numpy as np

P = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
WT = P / "production/word_timing.json"
OLD = P / "production/word_timing_v3_estimated.json"
if not OLD.exists():
    shutil.copy(WT, OLD)
old = json.loads(OLD.read_text())
ph = json.loads((P / "production/phoneme_timing.json").read_text())
D = old["video_duration"]

# ---- 100 Hz energy envelope of the real VO
raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(P / "assets/vo_elevenlabs_final.mp3"), "-ac", "1", "-ar", "16000", "-f", "s16le", "-"],
                     capture_output=True, check=True).stdout
a = np.frombuffer(raw, dtype=np.int16).astype(np.float64) / 32768
hop = 160
n = len(a) // hop
rms = np.sqrt(np.mean(a[: n * hop].reshape(n, hop) ** 2, axis=1))
db = 20 * np.log10(rms + 1e-6)

def frame(t):
    return max(0, min(n - 1, int(round(t * 100))))

words = old["words"]
pw = ph["words"]
phones = ph["phones"]
new_words = []
for k, w in enumerate(words):
    p = pw[k]
    my = [x for x in phones if x[3] == k]
    s = max(0.0, my[0][1] - 0.02)
    nxt = pw[k + 1]["start"] - 0.02 if k + 1 < len(pw) else old["audio"]["duration"]
    # end: first 30 ms run below -40 dB after the last phone onset (capped by the next word)
    e = None
    f = frame(my[-1][1] + 0.04)
    while f < n - 3 and f / 100 < nxt:
        if db[f] < -40 and db[f + 1] < -40 and db[f + 2] < -40:
            e = f / 100
            break
        f += 1
    if e is None:
        e = nxt
    e = max(e, my[-1][1] + 0.06)
    nw = dict(w, start=round(s, 3), end=round(min(e, nxt + 0.02), 3))
    nw["v3_start"], nw["v3_end"] = w["start"], w["end"]
    new_words.append(nw)

# phones with durations (onset -> next onset in the same word, last -> word end)
VP = []
for k, w in enumerate(new_words):
    my = [x for x in phones if x[3] == k]
    for j, x in enumerate(my):
        e = my[j + 1][1] if j + 1 < len(my) else w["end"]
        VP.append([x[0], round(x[1], 3), round(e, 3), k])

groups = []
for gi, g in enumerate(old["caption_groups"]):
    g = dict(g)
    a0 = g["word_idx"][0]
    g["start"] = 0.0 if gi == 0 else round(max(0.0, new_words[a0]["start"] - 0.12), 3)
    groups.append(g)
for gi, g in enumerate(groups):
    g["end"] = groups[gi + 1]["start"] if gi + 1 < len(groups) else D

out = dict(old)
out["words"] = new_words
out["caption_groups"] = groups
out["method"] = ("v4: MMS-300m CTC forced alignment on the real VO (ctc-forced-aligner, ONNX, local), character level on the "
                 "spoken form (production/phoneme_timing.json); word start = first phone onset - 20 ms; word end = first 30 ms "
                 "below -40 dB after the last phone (capped by the next word).")
out["accuracy"] = "Phone onsets on a 20 ms grid from the acoustic model; every word onset verified to sit on speech energy (> -38 dB)."
out["audio"] = dict(old["audio"], speech_onset=new_words[0]["start"], last_word_end=new_words[-1]["end"],
                    file_tail_silence=round(old["audio"]["duration"] - new_words[-1]["end"], 3))
WT.write_text(json.dumps(out, indent=1, ensure_ascii=False))

warp = [[w["v3_start"], w["start"]] for w in new_words]
(P / "production/timing_warp_v4.json").write_text(json.dumps({"note": "global old (v3 estimated) word start -> v4 measured word start", "pairs": warp}, indent=0))

# SFX apexes follow the words they belong to
def W(t):
    xs = [p[0] for p in warp]; ys = [p[1] for p in warp]
    return float(np.interp(t, xs, ys))
sp = P / "tools/sfx_plan.json"
sfx = json.loads(sp.read_text())
for x in sfx:
    if x["cue"].startswith(("v3 ", "v4 ")):
        continue  # v3 presenter cues are regenerated by gen_presenter
    if "v3_apex" not in x:
        x["v3_apex"] = x["apex"]
    na = round(W(x["v3_apex"]), 3)
    x["t"] = round(x["t"] + (na - x["apex"]), 3)
    x["apex"] = na
sp.write_text(json.dumps(sfx, indent=1))

# ---- runtime data for the mascot
keys = {i for g in groups for i in g["highlight"]}
PRON = ph["pronunciation_overrides"]
vw = []
for i, w in enumerate(new_words):
    vw.append([w["text"], w["start"], w["end"], 1 if i in keys else 0, ph["words"][i]["spoken"]])
env = np.clip((db + 60) / 60, 0, 1)  # 0 at -60 dB, 1 at 0 dB
env_q = [int(round(v * 99)) for v in env[: int(D * 100) + 1]]
js = ("// generated by tools/retime_v4.py — VO timing measured from the audio (CTC forced alignment + energy)\n"
      "window.VO_WORDS = " + json.dumps(vw, separators=(",", ":"), ensure_ascii=False) + ";\n"
      "window.VO_PHONES = " + json.dumps(VP, separators=(",", ":")) + ";\n"
      "window.VO_ENV = " + json.dumps(env_q, separators=(",", ":")) + "; // 100 Hz, 0..99 = -60..0 dB\n"
      "window.VO_WARP = " + json.dumps(warp, separators=(",", ":")) + ";\n")
(P / "vendor/vo_words.js").write_text(js)
d = [abs(a - b) for a, b in warp]
print(f"words {len(new_words)}, phones {len(VP)}, |shift| mean {np.mean(d):.3f}s max {max(d):.3f}s; sfx {len(sfx)}")
