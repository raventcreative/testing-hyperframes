"""VO loudness envelope at 30 fps (0..1) for voice-reactive visuals. Output: vendor/vo_env.js (window.VO_ENV)
Run: python3 -I tools/vo_env.py <project>"""
import json, subprocess, sys
from pathlib import Path
import numpy as np

P = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(P / "assets/audio/vo.wav"), "-ac", "1", "-ar", "24000", "-f", "s16le", "-"],
                     capture_output=True, check=True).stdout
x = np.frombuffer(raw, np.int16).astype(np.float32) / 32768
hop = 24000 // 30
rms = np.array([np.sqrt(np.mean(x[i:i + hop] ** 2) + 1e-12) for i in range(0, len(x) - hop, hop)])
db = 20 * np.log10(rms)
v = np.clip((db + 45) / (np.percentile(db, 97) + 45), 0, 1)
k = np.array([0.25, 0.5, 0.25])
v = np.convolve(v, k, mode="same")
(P / "vendor/vo_env.js").write_text("// generated by tools/vo_env.py\nwindow.VO_ENV = " + json.dumps([round(float(a), 3) for a in v]) + ";\n")
print(len(v), "frames")
