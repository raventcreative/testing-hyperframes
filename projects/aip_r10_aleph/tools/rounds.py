"""Builds vendor/rounds.js: window.TOTAL (video length) + window.SCN (scene start/duration) + window.DEMOS (the four before/after demo
beats: s02 night, s03 seasons, s04 car, s05 product; tReveal = the marker word). Run: python3 -I tools/rounds.py ."""
import json, sys
from pathlib import Path
P = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
T = json.loads((P / "production/timing.json").read_text()); W = T["words"]; S = {s["id"]: s for s in T["scenes"]}
R = []
for k, sid in enumerate(["s02", "s03", "s04", "s05"]):
    sc = S[sid]; ws = W[sc["w0"]:sc["w1"] + 1]
    mk = [w for w in ws if w["st"] == "m"]
    R.append({"k": k + 1, "id": sid, "start": sc["start"], "dur": sc["dur"], "tReveal": [w["s"] for w in mk], "words": [[w["w"], w["s"]] for w in ws]})
out = "// generated by tools/rounds.py (global times)\nwindow.DEMOS = " + json.dumps(R, separators=(",", ":")) + ";\n"
out += f"window.TOTAL = {T['total_sec']};\nwindow.SCN = " + json.dumps({k: [v["start"], v["dur"]] for k, v in S.items()}, separators=(",", ":")) + ";\n"
(P / "vendor/rounds.js").write_text(out)
for r in R: print(r["id"], r["start"], r["tReveal"])
