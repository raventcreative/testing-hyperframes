"""Generate every slide of the carousel from ONE config (carousel.json) + one folder per effect (effects/<id>/).

    python3 -I tools/build.py

- slides/sNN/index.html (one HyperFrames composition per slide: cover, one per effect, closing) + symlinks
  slides/sNN/vendor -> ../../vendor and slides/sNN/effects -> ../../effects (shared kit, demo code, photos)
- slides/manifest.json (slide list for tools/render.sh + tools/snap.sh)
- production/DM_ANIMASI.md (the DM hand-out: intro + every effect's prompt.md, in carousel order)
Counters ("02 / 17", "01 / 15 · ...") and the cover grid / closing list follow the number of effects in carousel.json.
"""
import html
import json
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GENERATED = {"index.html", "vendor", "effects"}


def words(text):
    return re.sub(r"\s+", " ", text).strip().split(" ")


def load_effect(eid):
    d = ROOT / "effects" / eid
    meta = json.loads((d / "meta.json").read_text())
    prompt = (d / "prompt.md").read_text().strip()
    for f in ("demo.js", "demo.css"):
        if not (d / f).exists():
            raise SystemExit(f"{eid}: missing {f}")
    meta["id"] = eid
    meta["prompt"] = prompt
    return meta


def page(comp, title, dur, css, js, slide):
    links = "\n".join(f'<link rel="stylesheet" href="{c}" />' for c in css)
    scripts = "\n".join(f'<script src="{s}"></script>' for s in js)
    data = json.dumps(slide, ensure_ascii=False, indent=1)
    return f"""<!doctype html>
<html lang="id">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=1080, height=1350" />
<title>{html.escape(title)} · AI PRENEUR</title>
<!-- GENERATED by tools/build.py from carousel.json + effects/<id>/ - edit those, then rebuild -->
<link rel="stylesheet" href="vendor/car.css" />
{links}
<script src="vendor/gsap.min.js"></script>
<script src="vendor/icons.js"></script>
<script src="vendor/car.js"></script>
{scripts}
</head>
<body>
<div id="root" data-composition-id="{comp}" data-start="0" data-duration="{dur}" data-width="1080" data-height="1350" data-fps="30">
  <div id="stage" class="clip" data-start="0" data-duration="{dur}" data-track-index="0"></div>
</div>
<script>
window.SLIDE = {data};
window.__timelines = window.__timelines || {{}};
window.__timelines["{comp}"] = CAR.run(window.SLIDE);
</script>
</body>
</html>
"""


def link(slide_dir, name):
    p = slide_dir / name
    target = Path("..") / ".." / name
    if p.is_symlink() and os.readlink(p) == str(target):
        return
    if p.is_symlink() or p.exists():
        p.unlink()
    p.symlink_to(target)


def main():
    cfg = json.loads((ROOT / "carousel.json").read_text())
    effects = [load_effect(e) for e in cfg["effects"]]
    n = len(effects)
    total = n + 2
    kw = cfg["keyword"]
    short = [{"id": e["id"], "short": e["short"], "icon": e["icon"]} for e in effects]
    fill = lambda s: s.replace("{N}", str(n)).replace("{KW}", kw)   # noqa: E731
    cover = {k: fill(v) for k, v in cfg["cover"].items()}
    closing = {k: (fill(v) if isinstance(v, str) else [[fill(x) for x in s] for s in v]) for k, v in cfg["closing"].items()}
    slides = []
    # cover
    slides.append(dict(kind="cover", title=cover["title1"] + " " + cover["title2"], duration=cfg["coverDuration"], still=cfg.get("coverStill", 3.0),
                       css=[f"effects/{e['id']}/demo.css" for e in effects],
                       js=[f"effects/{e['id']}/{s}" for e in effects for s in e.get("scripts", [])] + [f"effects/{e['id']}/demo.js" for e in effects],
                       extra={"cover": cover, "effects": short, "swipe": cfg["swipe"]["cover"]}))
    for i, e in enumerate(effects):
        w = words(e["prompt"])
        lead_n = e.get("leadWords", 7)
        slides.append(dict(kind="effect", title=e["title"], duration=cfg["slideDuration"], still=e.get("still", 3.0),
                           css=[f"effects/{e['id']}/demo.css"],
                           js=[f"effects/{e['id']}/{s}" for s in e.get("scripts", [])] + [f"effects/{e['id']}/demo.js"],
                           extra={"effect": e["id"], "num": f"{i + 1:02d}", "count": f"{n:02d}", "category": e["category"], "icon": e["icon"],
                                  "title": e["title"], "titleSize": e.get("titleSize", 92), "subtitle": e["subtitle"], "use": e["use"], "url": e["url"],
                                  "promptLead": html.escape(" ".join(w[:lead_n])), "promptRest": html.escape(" ".join(w[lead_n:lead_n + 16])),
                                  "swipe": cfg["swipe"]["last" if i == n - 1 else "effect"]}))
    slides.append(dict(kind="closing", title=closing["title1"] + " " + closing["title2"], duration=cfg["slideDuration"], still=cfg.get("closingStill", 3.0),
                       css=[], js=[], extra={"closing": closing, "effects": short, "swipe": cfg["swipe"]["closing"], "swipeIcon": "bookmark"}))

    out = ROOT / "slides"
    out.mkdir(exist_ok=True)
    manifest = []
    for idx, s in enumerate(slides, start=1):
        comp = f"s{idx:02d}"
        d = out / comp
        d.mkdir(exist_ok=True)
        link(d, "vendor")
        link(d, "effects")
        slide = {"comp": comp, "kind": s["kind"], "index": idx, "total": total, "duration": s["duration"], "keyword": kw}
        slide.update(s["extra"])
        (d / "index.html").write_text(page(comp, s["title"], s["duration"], s["css"], s["js"], slide))
        manifest.append({"slide": idx, "dir": f"slides/{comp}", "kind": s["kind"], "effect": s["extra"].get("effect"), "title": s["title"],
                         "duration": s["duration"], "still": s["still"], "out": f"{cfg['outPrefix']}{idx:02d}"})
    # remove slide folders left over from a longer carousel (only our generated files)
    for d in sorted(out.glob("s[0-9][0-9]")):
        if int(d.name[1:]) > total:
            names = {p.name for p in d.iterdir()} - {".hyperframes"}
            if names <= GENERATED:
                for name in names:
                    (d / name).unlink()
                if not any(d.iterdir()):
                    d.rmdir()
                print("removed stale", d.name)
            else:
                print("WARNING stale slide folder with extra files, left alone:", d)
    (out / "manifest.json").write_text(json.dumps(manifest, indent=1, ensure_ascii=False))

    # DM hand-out
    dm = [fill(cfg["dm"]["title"]), "", fill(cfg["dm"]["intro"]), ""]
    for i, e in enumerate(effects, start=1):
        dm += [f"## {i:02d} · {e['title'].rstrip('.')}", "", f"**{e['category']}** · cocok buat: {e['use']}", "", "```text", e["prompt"], "```", ""]
    dm += [fill(cfg["dm"]["outro"]), ""]
    (ROOT / "production" / "DM_ANIMASI.md").write_text("\n".join(dm))
    print(f"built {len(slides)} slides ({n} effects) -> slides/, production/DM_ANIMASI.md")


if __name__ == "__main__":
    main()
