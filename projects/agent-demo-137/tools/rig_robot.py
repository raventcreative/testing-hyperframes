"""Split the cut-out robot into a puppet rig: body (head + shoulders + left hand) and the free-floating right hand,
plus eye boxes for blinking and light positions. Coordinates are written in display pixels for a 560 px wide robot.
Run: python3 -I tools/cutout_robot.py assets/robot/robot_src.webp /tmp/robot_full.png
     python3 -I tools/rig_robot.py /tmp/robot_full.png <project>"""
import json, sys
from collections import deque
from pathlib import Path
import numpy as np
from PIL import Image, ImageFilter

src, P = sys.argv[1], Path(sys.argv[2]).resolve()
im = Image.open(src).convert("RGBA"); a = np.asarray(im).copy(); H, W = a.shape[:2]
solid = a[..., 3] > 60
lab = np.zeros((H, W), np.int32); n = 0; comps = []
for sy, sx in zip(*np.nonzero(solid)):
    if lab[sy, sx]: continue
    n += 1; lab[sy, sx] = n; dq = deque([(sy, sx)]); c = 0
    while dq:
        y, x = dq.popleft(); c += 1
        for ny, nx in ((y - 1, x), (y + 1, x), (y, x - 1), (y, x + 1)):
            if 0 <= ny < H and 0 <= nx < W and solid[ny, nx] and not lab[ny, nx]: lab[ny, nx] = n; dq.append((ny, nx))
    comps.append((c, n))
comps.sort(reverse=True)
hand_id = comps[1][1]                                     # second-largest part = free right hand
hand = np.asarray(Image.fromarray(((lab == hand_id) * 255).astype(np.uint8)).filter(ImageFilter.MaxFilter(5))) > 0
ys, xs = np.nonzero(hand); hx0, hy0, hx1, hy1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
handimg = a.copy(); handimg[~hand, 3] = 0
body = a.copy(); body[hand, 3] = 0
EX = 0.6                                                   # export scale (sharp enough for 560 px display)
F = 560 / W                                                # display scale
out = P / "assets/robot"; out.mkdir(parents=True, exist_ok=True)
Image.fromarray(body).resize((round(W * EX), round(H * EX)), Image.LANCZOS).save(out / "body.png", optimize=True)
Image.fromarray(handimg[hy0:hy1, hx0:hx1]).resize((round((hx1 - hx0) * EX), round((hy1 - hy0) * EX)), Image.LANCZOS).save(out / "hand.png", optimize=True)
box = lambda x0, y0, x1, y1: [round(x0 * F, 1), round(y0 * F, 1), round((x1 - x0) * F, 1), round((y1 - y0) * F, 1)]
rig = {"w": 560, "h": round(H * F), "hand": box(hx0, hy0, hx1, hy1),
       "eyes": [box(563, 210, 647, 345), box(758, 186, 828, 316)],
       "chest": box(360, 650, 803, 735), "base": box(418, 990, 669, 1024)}
(P / "vendor/robot_rig.js").write_text("// generated by tools/rig_robot.py\nwindow.ROBOT_RIG = " + json.dumps(rig) + ";\n")
print(rig)
