"""production/plugins.json -> vendor/plugins_data.js (logo or monogram, stars, README preview). Run: python3 -I tools/build_data.py ."""
import json, sys
from pathlib import Path
P = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
PL = json.loads((P / "production/plugins.json").read_text())
LOGO_OK = {3, 6, 8, 14, 15, 16, 17, 18, 22, 24, 26}           # project/org logos (no personal photos)
MONO = {0: "Sp", 1: "MP", 2: "ECC", 4: "Pt", 5: "AS", 7: "AR", 9: "30", 10: "CO", 11: "REA", 12: "gs", 13: "Cv", 19: "Ta",
        20: "Ar", 21: "Im", 23: "Dd", 25: "OM", 27: "Hu", 28: "AD", 29: "MS"}
CATS = [{"id": "c1", "num": "01", "tab": "Coding", "t1": "Ngoding kayak", "t2": "senior dev", "col": "#16a06a", "tint": "#e3f5ec"},
        {"id": "c2", "num": "02", "tab": "Riset", "t1": "Riset &", "t2": "pahami apa pun", "col": "#2c68d8", "tint": "#e4ecfb"},
        {"id": "c3", "num": "03", "tab": "Hemat token", "t1": "Project gede,", "t2": "token hemat", "col": "#e0732a", "tint": "#fcebdd"},
        {"id": "c4", "num": "04", "tab": "Desain", "t1": "Desain &", "t2": "visual", "col": "#7b4fd6", "tint": "#eee6fb"},
        {"id": "c5", "num": "05", "tab": "Konten", "t1": "Nulis &", "t2": "bikin video", "col": "#d4437c", "tint": "#fbe5ee"}]
def fmt(s):
    if s is None: return None
    return f"{s/1000:.1f}k".replace(".0k", "k") if s < 1_000_000 else f"{s/1e6:.1f}M"
out = []
for i, p in enumerate(PL):
    img = P / f"assets/readme/{i:02d}.jpg"
    out.append({"i": i, "cat": p["cat"], "name": p["name"], "repo": p["repo"], "desc": p["id"], "stars": p.get("stars"), "starsTxt": fmt(p.get("stars")),
                "logo": f"assets/logos/{i:02d}.png" if i in LOGO_OK else None, "mono": MONO.get(i), "readme": f"assets/readme/{i:02d}.jpg" if img.exists() else None})
total = sum(p["stars"] or 0 for p in out)
(P / "vendor/plugins_data.js").write_text("// generated by tools/build_data.py from live GitHub data\nwindow.PLUGINS = " + json.dumps(out, ensure_ascii=False) +
    ";\nwindow.CATS = " + json.dumps(CATS, ensure_ascii=False) + f";\nwindow.TOTAL_STARS = {total};\n")
print("total stars", total, "| readme", sum(1 for p in out if p["readme"]), "| logos", sum(1 for p in out if p["logo"]))
