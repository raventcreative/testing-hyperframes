"""Time warp new VO take -> the timeline the scenes were built on (take 2, production/words_take2.json).
The scenes (vendor/vx.js), page timeline (titles, tags, flashes) and SFX were keyed to take 2. Take 4 (final, untouched) only
re-worded two lines, so its words are matched to take 2 word by word (difflib) and a monotonic piecewise-linear map
new composition time -> take-2 composition time is written to vendor/warp.js (window.WARP, window.WARPINV).
The VO itself is never cut or stretched: the PICTURE follows the voice."""
import json, re, difflib
OFF = 0.3
A = json.load(open("production/words_take2.json")); B = json.load(open("production/words.json"))
n = lambda w: re.sub(r"[^a-z0-9]", "", w.lower())
sm = difflib.SequenceMatcher(a=[n(w[0]) for w in B], b=[n(w[0]) for w in A], autojunk=False)
P = [(0.0, 0.0)]
for blk in sm.get_matching_blocks():
    for k in range(blk.size):
        tn, to = B[blk.a + k][1] + OFF, A[blk.b + k][1] + OFF
        if tn > P[-1][0] + 0.02 and to > P[-1][1] + 0.02: P.append((round(tn, 3), round(to, 3)))
P.append((P[-1][0] + 5, P[-1][1] + 5))
d = [round(o - nn, 2) for nn, o in P]
print(len(P), "anchors; old-new offset min/max", min(d), max(d))
js = "// generated by tools/warp.py: final VO take (composition time) -> take-2 timeline the scenes were keyed to\n"
js += "window.WARP_PTS = " + json.dumps(P) + ";\n"
js += """(function () { const P = window.WARP_PTS;
  const f = (x, i, j) => { if (x <= P[0][i]) return x - P[0][i] + P[0][j];
    for (let k = 1; k < P.length; k++) if (x <= P[k][i]) { const a = P[k - 1], b = P[k]; return a[j] + (b[j] - a[j]) * (x - a[i]) / (b[i] - a[i]); }
    const L = P[P.length - 1]; return x - L[i] + L[j]; };
  window.WARP = (x) => f(x, 0, 1); window.WARPINV = (x) => f(x, 1, 0); })();
"""
open("vendor/warp.js", "w").write(js)
json.dump(P, open("production/warp_points.json", "w"))
