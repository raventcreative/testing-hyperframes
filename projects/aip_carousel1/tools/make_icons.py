"""Generate vendor/icons.js (inner SVG of the lucide-static 0.460.0 icons we use, ISC licence).
Usage: python3 -I tools/make_icons.py <path to lucide-static/package/icons>"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAMES = """sparkles message-circle message-circle-more arrow-right chevron-right chevron-down chevron-left plus minus check circle-check
star shopping-cart shopping-bag heart lock eye map-pin truck package clock tag percent gift ticket copy x menu search user phone house
calendar badge-check flame zap shield-check store scissors camera leaf coffee cookie utensils bookmark send timer bell info hand
list-checks credit-card wallet smile circle-help refresh-cw globe navigation box layers mail badge-percent circle-dollar-sign
cake-slice sprout flower-2 footprints wind shirt shopping-basket receipt-text party-popper hourglass thumbs-up quote panel-bottom
mouse-pointer-click arrow-up arrow-down move-down chevrons-down headset ruler map file-text folder-open clipboard-list
""".split()


def main():
    src = Path(sys.argv[1])
    out, missing = [], []
    for n in NAMES:
        f = src / f"{n}.svg"
        if not f.exists():
            missing.append(n)
            continue
        t = f.read_text()
        inner = re.search(r"<svg[^>]*>(.*)</svg>", t, re.S).group(1)
        inner = re.sub(r"\s+", " ", inner).strip()
        out.append('"%s": "%s"' % (n, inner.replace('"', '\\"')))
    if missing:
        raise SystemExit("missing icons: " + " ".join(missing))
    js = "// generated by tools/make_icons.py: lucide-static 0.460.0 (ISC licence, vendor/LICENSE-lucide.txt)\nwindow.CAR_ICO = {\n" + ",\n".join(out) + "\n};\n"
    (ROOT / "vendor" / "icons.js").write_text(js)
    print("icons", len(out))


if __name__ == "__main__":
    main()
