def minireel_anim(S, id_, a, b, period=1.6, amp=1.0):
    """keep a mini Reel alive between global a..b: cards drift/flip, dot orbits, caption bars type in.
    finite repeats only; every tween is fromTo."""
    t = a
    k = 0
    while t < b - 0.05:
        d = min(period, b - t)
        sgn = 1 if k % 2 == 0 else -1
        S.ft(f"#{id_}-a", {"y": 0, "rotation": 0}, {"y": -8 * amp * sgn, "rotation": 1.5 * sgn * amp}, t, d, "sine.inOut")
        S.ft(f"#{id_}-b", {"x": 0, "scale": 1}, {"x": 10 * amp * sgn, "scale": 1 + 0.04 * amp}, t, d, "sine.inOut")
        S.ft(f"#{id_}-d", {"x": 0, "y": 0}, {"x": -14 * amp * sgn, "y": 10 * amp}, t, d, "sine.inOut")
        S.ft(f"#{id_}-c1", {"scaleX": 0.35, "transformOrigin": "0% 50%"}, {"scaleX": 1}, t, min(0.5, d), "power3.out")
        S.ft(f"#{id_}-e", {"scaleX": 0.2, "transformOrigin": "0% 50%"}, {"scaleX": 1}, t + 0.15, min(0.5, d), "power3.out")
        t += d
        k += 1


def apex(S, layer, id_, x, y, at, size=520, ring=True, sparks=0, seed=7, op=0.85):
    """one controlled light burst (+ ring + seeded sparkles) centred at (x, y)."""
    layer.append(f'<div class="bloom" id="{id_}-bl" style="{box(x - size / 2, y - size / 2, size, size)}"></div>')
    S.init(f"#{id_}-bl", {"opacity": 0, "scale": 0.3})
    S.ft(f"#{id_}-bl", {"opacity": 0, "scale": 0.3}, {"opacity": op, "scale": 0.9}, at - 0.06, 0.12, "power2.in")
    S.ft(f"#{id_}-bl", {"opacity": op, "scale": 0.9}, {"opacity": 0, "scale": 1.35}, at + 0.06, 0.45, "power2.out")
    if ring:
        rs = size * 0.42
        layer.append(f'<div class="ring" id="{id_}-rg" style="{box(x - rs / 2, y - rs / 2, rs, rs)}"></div>')
        S.init(f"#{id_}-rg", {"opacity": 0, "scale": 0.3})
        S.ft(f"#{id_}-rg", {"opacity": 0.95, "scale": 0.3}, {"opacity": 0, "scale": 2.4}, at, 0.55, "power3.out")
    R = Rng(seed)
    for k in range(sparks):
        ang = 2 * math.pi * (k + R.u(0, 0.6)) / sparks
        dist = R.u(size * 0.22, size * 0.42)
        sid = f"{id_}-sp{k}"
        layer.append(f'<div class="spark" id="{sid}" style="left:{r3(x - 7)}px;top:{r3(y - 7)}px"></div>')
        S.init(f"#{sid}", {"opacity": 0, "scale": 0.2})
        S.ft(f"#{sid}", {"opacity": 0, "x": 0, "y": 0, "scale": 0.2, "rotation": 0},
             {"opacity": 1, "x": r3(dist * math.cos(ang) * 0.6), "y": r3(dist * math.sin(ang) * 0.6), "scale": 1.1, "rotation": 45}, at + 0.02, 0.22, "power3.out")
        S.ft(f"#{sid}", {"opacity": 1, "x": r3(dist * math.cos(ang) * 0.6), "y": r3(dist * math.sin(ang) * 0.6), "scale": 1.1, "rotation": 45},
             {"opacity": 0, "x": r3(dist * math.cos(ang)), "y": r3(dist * math.sin(ang)), "scale": 0.3, "rotation": 90}, at + 0.24, 0.4, "power2.in")


