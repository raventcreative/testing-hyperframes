"""Inline the open-source icons (Lucide ISC, Simple Icons CC0) into vendor/icons.js so the page needs no fetch.
Run: python3 -I tools/build_icons.py <project>"""
import json, re, sys
from pathlib import Path

P = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
icons = {}
for f in sorted((P / "assets/icons/lu").glob("*.svg")):
    body = re.sub(r"<!--.*?-->", "", f.read_text(), flags=re.S)
    inner = re.search(r"<svg[^>]*>(.*)</svg>", body, re.S).group(1)
    icons[f.stem] = ("lu", " ".join(inner.split()))
for f in sorted((P / "assets/icons/si").glob("*.svg")):
    inner = re.search(r"<svg[^>]*>(.*)</svg>", f.read_text(), re.S).group(1)
    inner = re.sub(r"<title>.*?</title>", "", inner)
    icons["si-" + f.stem] = ("si", inner)
(P / "vendor/icons.js").write_text("// generated by tools/build_icons.py (Lucide ISC, Simple Icons CC0)\nwindow.ICONS = " +
                                   json.dumps(icons) + ";\n")
print(len(icons), "icons")
