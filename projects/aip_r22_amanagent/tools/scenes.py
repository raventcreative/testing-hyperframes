"""Builds vendor/scenes.js (window.TOTAL, window.SCN = {id: [start, dur]}) from production/timing.json, so every scene composition
reads its own global start/duration instead of hard-coding them (re-timing the VO = re-run timing.py + this + build_index.py).
Run: python3 -I tools/scenes.py ."""
import json, sys
from pathlib import Path
P = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
T = json.loads((P / "production/timing.json").read_text())
S = {s["id"]: [s["start"], s["dur"]] for s in T["scenes"]}
out = "// generated by tools/scenes.py (global times)\n"
out += f"window.TOTAL = {T['total_sec']};\nwindow.SCN = " + json.dumps(S, separators=(",", ":")) + ";\n"
(P / "vendor/scenes.js").write_text(out)
for k, (a, d) in S.items(): print(k, a, d, round(a + d, 4))
