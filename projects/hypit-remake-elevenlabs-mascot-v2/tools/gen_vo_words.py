"""Writes vendor/vo_words.js (window.VO_WORDS) from production/word_timing.json for the mascot lip sync / talk layer."""
import json, sys
from pathlib import Path
P = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
wt = json.loads((P / "production/word_timing.json").read_text())
keys = {i for g in wt["caption_groups"] for i in g["highlight"]}
out = []
for i, w in enumerate(wt["words"]):
    phon = {"HYPIT.": "haipit", "Hypit,": "haipit", "Hypit": "haipit", "Claude": "klod", "B-roll,": "biroll", "AI": "ei ai"}.get(w["text"])
    out.append([w["text"], round(w["start"], 3), round(w["end"], 3), 1 if i in keys else 0] + ([phon] if phon else []))
(P / "vendor/vo_words.js").write_text("// generated by tools/gen_vo_words.py from production/word_timing.json — [text, start, end, keyword, phon?]\nwindow.VO_WORDS = " + json.dumps(out, separators=(",", ":")) + ";\n")
print(len(out), "words,", len(keys), "keywords")
